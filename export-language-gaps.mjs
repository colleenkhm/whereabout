// Writes docs/language-percentage-gaps.md: every country without a
// verified language percentage, plus every figure under non-commercial
// terms, from the spreadsheet's Languages tab.
// Usage: node export-language-gaps.mjs
import XLSX from 'xlsx';
import { writeFileSync } from 'fs';

const SHEET = 'whereabout-data-collection.xlsx';
const OUT = 'docs/language-percentage-gaps.md';

const rows = XLSX.utils
  .sheet_to_json(XLSX.readFile(SHEET).Sheets.Languages, { defval: null })
  .filter((r) => r.country_code && r.language_code);

const byCountry = new Map();
for (const r of rows) {
  if (!byCountry.has(r.country_code)) byCountry.set(r.country_code, []);
  byCountry.get(r.country_code).push(r);
}

const fold = (s) => s.normalize('NFKD').replace(/[\u0300-\u036f]/g, '').toLowerCase();
const clip = (s, n = 220) => (s.length > n ? `${s.slice(0, n - 1).trimEnd()}…` : s);
const cell = (s) => s.replace(/\|/g, '/').replace(/\s+/g, ' ').trim();

const gaps = [...byCountry.values()]
  .filter((ls) => !ls.some((l) => l.status === 'verified'))
  .sort((a, b) => fold(a[0].country_name).localeCompare(fold(b[0].country_name)));

// Coarse state, from statuses and note markers.
const state = (ls) => {
  const notes = ls.map((l) => l.notes ?? '').join(' ');
  if (/HELD \(licence\)/.test(notes)) return 'held (licence)';
  if (/blocked access/.test(notes)) return 'blocked';
  if (ls.every((l) => l.status === 'no_source')) return 'no source';
  if (ls.some((l) => l.status === 'no_source')) return 'partly checked';
  return 'not researched';
};

const lines = gaps.map((ls) => {
  const langs = ls.map((l) => `${l.language_name} (${l.status})`).join(', ');
  const notes = [...new Set(ls.map((l) => l.notes).filter(Boolean))];
  const why = notes.length ? clip(notes.join(' ')) : '';
  return `| ${cell(ls[0].country_name)} | ${state(ls)} | ${cell(langs)} | ${cell(why)} |`;
});

// Rows whose notes carry the NON-COMMERCIAL marker.
const nonCommercial = rows
  .filter((r) => /NON-COMMERCIAL/.test(r.notes ?? ''))
  .sort((a, b) => fold(a.country_name).localeCompare(fold(b.country_name)))
  .map((r) => `| ${cell(r.country_name)} | ${cell(r.language_name)} | ${r.percent_speakers ?? ''} | ${r.status} | ${cell(r.notes.match(/NON-COMMERCIAL:[^;]*/)[0])} |`);

const withBar = byCountry.size - gaps.length;
const tally = {};
for (const ls of gaps) tally[state(ls)] = (tally[state(ls)] ?? 0) + 1;
const counts = Object.entries(tally).map(([k, v]) => `${k} ${v}`).join(', ');
writeFileSync(
  OUT,
  `# Countries without language percentages

Generated by \`node export-language-gaps.mjs\` from the spreadsheet's
Languages tab; don't edit by hand. Re-run after every language batch.

${gaps.length} of ${byCountry.size} countries have no verified percentage
(${withBar} have at least one bar). By state: ${counts}.

- **not researched**: no batch has checked it yet. \`unverified\` rows here
  are old Wikipedia figures, never shown.
- **partly checked**: some languages checked and found to have no source.
- **no source**: every language checked, none has a speaking figure.
- **held (licence)**: a figure exists but the source's terms block reuse.
- **blocked**: the source site blocks automated access (skipped by
  direction 2026-11-18).

Notes are the rows' \`notes\`, clipped. Batch-level causes are in
HANDOFF.md and the scratch notes' Known data gaps.

| Country | State | Languages (status) | Notes |
|---|---|---|---|
${lines.join('\n')}

## Figures in use under non-commercial terms

Allowed while whereabout isn't commercial (direction 2026-11-18). Every one
must be removed, or permission obtained, before any commercial use. Marked
by \`NON-COMMERCIAL:\` in the row's \`notes\`.

| Country | Language | % | Status | Terms |
|---|---|---|---|---|
${nonCommercial.join('\n')}
`,
);
console.log(`${gaps.length} countries without a bar, ${nonCommercial.length} non-commercial rows -> ${OUT}`);
